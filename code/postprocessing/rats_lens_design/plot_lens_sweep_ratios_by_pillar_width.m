function plot_lens_sweep_ratios_by_pillar_width( ...
    ratioDir, outputDir)

if ~isfolder(outputDir)
    mkdir(outputDir);
end

dbLevels = [6, 12];
fontName = 'Arial';
axisLabelSize = 21;
tickLabelSize = 18;
legendSize = 18;
lineWidth = 1.2;

for dbLevel = dbLevels
    tablePath = fullfile( ...
        ratioDir, ...
        sprintf('pressure_ratios_%ddb.csv', dbLevel));
    ratios = readtable(tablePath);

    condition = string(ratios.condition);
    noLensRatio = ratios.ratio(condition == "nolens");
    noLensRatio = noLensRatio(1);

    pillared = ratios( ...
        condition == "pillared_lens" & ...
        ratios.corrected == 1, :);

    heights = sort(unique( ...
        pillared.nominal_thickness_mm));
    pillarWidths = sort(unique( ...
        pillared.pillar_width_mm));

    ratioMean = nan( ...
        numel(heights), numel(pillarWidths));
    ratioStd = nan( ...
        numel(heights), numel(pillarWidths));

    for heightIndex = 1:numel(heights)
        for widthIndex = 1:numel(pillarWidths)
            selected = ...
                pillared.nominal_thickness_mm == ...
                heights(heightIndex) & ...
                pillared.pillar_width_mm == ...
                pillarWidths(widthIndex);
            values = pillared.ratio(selected);
            ratioMean(heightIndex, widthIndex) = ...
                mean(values);
            ratioStd(heightIndex, widthIndex) = ...
                std(values);
        end
    end

    colors = slanCM('prism2', numel(heights));

    figureHandle = figure( ...
        'Visible', 'off', ...
        'Color', 'w', ...
        'Position', [930, 610, 830, 580]);
    axesHandle = axes(figureHandle);
    hold(axesHandle, 'on');

    xLimits = [0, max(pillarWidths) + 0.5];
    xSupport = linspace(xLimits(1), xLimits(2), 300);
    plot( ...
        axesHandle, ...
        xSupport, ...
        repmat(noLensRatio, size(xSupport)), ...
        'k--', ...
        'LineWidth', lineWidth, ...
        'DisplayName', 'No lens');

    for heightIndex = 1:numel(heights)
        errorbar( ...
            axesHandle, ...
            pillarWidths, ...
            ratioMean(heightIndex, :), ...
            ratioStd(heightIndex, :), ...
            '-o', ...
            'Color', colors(heightIndex, :), ...
            'LineWidth', lineWidth, ...
            'MarkerSize', 8, ...
            'MarkerFaceColor', colors(heightIndex, :), ...
            'DisplayName', ...
            sprintf('%.1f mm', heights(heightIndex)));
    end

    xlabel( ...
        axesHandle, ...
        'Pillar width (mm)', ...
        'FontName', fontName, ...
        'FontSize', axisLabelSize);
    ylabel( ...
        axesHandle, ...
        'Pressure ratio', ...
        'FontName', fontName, ...
        'FontSize', axisLabelSize);

    legendHandle = legend( ...
        axesHandle, ...
        'Location', 'southoutside', ...
        'NumColumns', 3);
    title(legendHandle, 'Maximum lens height');
    set( ...
        legendHandle, ...
        'Box', 'off', ...
        'Color', 'none', ...
        'FontName', fontName, ...
        'FontSize', legendSize);
    set( ...
        legendHandle.Title, ...
        'FontWeight', 'normal', ...
        'FontName', fontName, ...
        'FontSize', legendSize);

    upperValues = ratioMean + ratioStd;
    yMaximum = 1.1 * max( ...
        [noLensRatio; upperValues(:)]);
    xlim(axesHandle, xLimits);
    xticks(axesHandle, pillarWidths);
    ylim(axesHandle, [0, yMaximum]);
    set( ...
        axesHandle, ...
        'Box', 'off', ...
        'FontName', fontName, ...
        'FontSize', tickLabelSize, ...
        'LineWidth', lineWidth, ...
        'XColor', 'k', ...
        'YColor', 'k');

    outputBase = fullfile( ...
        outputDir, ...
        sprintf( ...
        'pressure_ratios_by_pillar_width_%ddb', ...
        dbLevel));
    savefig(figureHandle, [outputBase, '.fig']);
    exportgraphics( ...
        figureHandle, ...
        [outputBase, '.png'], ...
        'Resolution', 300);
    exportgraphics( ...
        figureHandle, ...
        [outputBase, '.svg'], ...
        'ContentType', 'vector');
    close(figureHandle);
end
end
