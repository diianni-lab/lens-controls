function plot_lens_sweep_ratios_by_height( ...
    ratioDir, outputDir)

if ~isfolder(outputDir)
    mkdir(outputDir);
end

dbLevels = [6, 12];
selectedPillarWidths = [1.5, 2.0, 2.5];
fontName = 'Arial';
axisLabelSize = 21;
tickLabelSize = 18;
legendSize = 18;
lineWidth = 1.2;

for dbLevel = dbLevels
    tablePath = fullfile( ...
        ratioDir, ...
        sprintf('pressure_ratios_%ddb.csv', dbLevel));
    ratios = readtable(tablePath);

    condition = string(ratios.condition);
    noLensRatio = ratios.ratio(condition == "nolens");
    noLensRatio = noLensRatio(1);

    flat = ratios( ...
        condition == "flat_lens" & ...
        ratios.corrected == 1, :);
    pillared = ratios( ...
        condition == "pillared_lens" & ...
        ratios.corrected == 1, :);

    heights = sort(unique( ...
        pillared.nominal_thickness_mm));
    flatRatio = nan(size(heights));
    ratioMean = nan( ...
        numel(heights), numel(selectedPillarWidths));
    ratioStd = nan( ...
        numel(heights), numel(selectedPillarWidths));

    for heightIndex = 1:numel(heights)
        selectedFlat = ...
            flat.nominal_thickness_mm == ...
            heights(heightIndex);
        flatRatio(heightIndex) = ...
            mean(flat.ratio(selectedFlat));

        for widthIndex = 1:numel(selectedPillarWidths)
            selectedPillared = ...
                pillared.nominal_thickness_mm == ...
                heights(heightIndex) & ...
                pillared.pillar_width_mm == ...
                selectedPillarWidths(widthIndex);
            values = pillared.ratio(selectedPillared);
            ratioMean(heightIndex, widthIndex) = ...
                mean(values);
            ratioStd(heightIndex, widthIndex) = ...
                std(values);
        end
    end

    colors = slanCM('prism2', 8);

    figureHandle = figure( ...
        'Visible', 'off', ...
        'Color', 'w', ...
        'Position', [930, 610, 830, 580]);
    axesHandle = axes(figureHandle);
    hold(axesHandle, 'on');

    xPadding = 0.25;
    xLimits = [ ...
        min(heights) - xPadding, ...
        max(heights) + xPadding];
    xSupport = linspace(xLimits(1), xLimits(2), 300);
    plot( ...
        axesHandle, ...
        xSupport, ...
        repmat(noLensRatio, size(xSupport)), ...
        'k--', ...
        'LineWidth', lineWidth, ...
        'DisplayName', 'No lens');
    plot( ...
        axesHandle, ...
        heights, ...
        flatRatio, ...
        'b-', ...
        'LineWidth', lineWidth, ...
        'DisplayName', 'Flat lens');

    for widthIndex = 1:numel(selectedPillarWidths)
        errorbar( ...
            axesHandle, ...
            heights, ...
            ratioMean(:, widthIndex), ...
            ratioStd(:, widthIndex), ...
            '-o', ...
            'Color', colors(widthIndex, :), ...
            'LineWidth', lineWidth, ...
            'MarkerSize', 8, ...
            'MarkerFaceColor', colors(widthIndex, :), ...
            'DisplayName', ...
            sprintf( ...
            '%.1f-mm pillars', ...
            selectedPillarWidths(widthIndex)));
    end

    xlabel( ...
        axesHandle, ...
        'Maximum lens height (mm)', ...
        'FontName', fontName, ...
        'FontSize', axisLabelSize);
    ylabel( ...
        axesHandle, ...
        'Pressure ratio', ...
        'FontName', fontName, ...
        'FontSize', axisLabelSize);

    legendHandle = legend( ...
        axesHandle, ...
        'Location', 'southoutside', ...
        'NumColumns', 3);
    title(legendHandle, 'Pillar width');
    set( ...
        legendHandle, ...
        'Box', 'off', ...
        'Color', 'none', ...
        'FontName', fontName, ...
        'FontSize', legendSize);
    set( ...
        legendHandle.Title, ...
        'FontWeight', 'normal', ...
        'FontName', fontName, ...
        'FontSize', legendSize);

    upperValues = ratioMean + ratioStd;
    yMaximum = 1.1 * max( ...
        [noLensRatio; flatRatio(:); upperValues(:)]);
    xlim(axesHandle, xLimits);
    xticks(axesHandle, heights);
    ylim(axesHandle, [0, yMaximum]);
    set( ...
        axesHandle, ...
        'Box', 'off', ...
        'FontName', fontName, ...
        'FontSize', tickLabelSize, ...
        'LineWidth', lineWidth, ...
        'XColor', 'k', ...
        'YColor', 'k');

    outputBase = fullfile( ...
        outputDir, ...
        sprintf( ...
        'pressure_ratios_by_height_%ddb', ...
        dbLevel));
    savefig(figureHandle, [outputBase, '.fig']);
    exportgraphics( ...
        figureHandle, ...
        [outputBase, '.png'], ...
        'Resolution', 300);
    exportgraphics( ...
        figureHandle, ...
        [outputBase, '.svg'], ...
        'ContentType', 'vector');
    close(figureHandle);
end
end
