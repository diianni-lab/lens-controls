function sampled = resampleVolume( ...
    volume, sourceGeometry, ...
    kgrid, gridGeometry, ...
    method, outsideValue)

sourceSize = size(volume);
interpolant = griddedInterpolant( ...
    {1:sourceSize(1), ...
    1:sourceSize(2), ...
    1:sourceSize(3)}, ...
    single(volume), method, 'none');

[xKwaveM, yKwaveM, zKwaveM] = ndgrid( ...
    single(kgrid.x_vec), ...
    single(kgrid.y_vec), ...
    single(kgrid.z_vec));

transformM = ...
    single(gridGeometry.worldFromKwaveM);

xWorldMm = 1e3 .* ( ...
    transformM(1, 1) .* xKwaveM + ...
    transformM(1, 2) .* yKwaveM + ...
    transformM(1, 3) .* zKwaveM + ...
    transformM(1, 4));
yWorldMm = 1e3 .* ( ...
    transformM(2, 1) .* xKwaveM + ...
    transformM(2, 2) .* yKwaveM + ...
    transformM(2, 3) .* zKwaveM + ...
    transformM(2, 4));
zWorldMm = 1e3 .* ( ...
    transformM(3, 1) .* xKwaveM + ...
    transformM(3, 2) .* yKwaveM + ...
    transformM(3, 3) .* zKwaveM + ...
    transformM(3, 4));

clear xKwaveM yKwaveM zKwaveM

originMm = single( ...
    1e3 * sourceGeometry.originM);
spacingMm = single( ...
    1e3 * sourceGeometry.spacingM);

iSource = ...
    (xWorldMm - originMm(1)) ./ spacingMm(1) + 1;
jSource = ...
    (yWorldMm - originMm(2)) ./ spacingMm(2) + 1;
kSource = ...
    (zWorldMm - originMm(3)) ./ spacingMm(3) + 1;

clear xWorldMm yWorldMm zWorldMm

sampled = single(interpolant( ...
    iSource, jSource, kSource));

outside = ~isfinite(sampled);
sampled(outside) = single(outsideValue);
end
