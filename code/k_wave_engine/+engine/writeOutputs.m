function result = writeOutputs( ...
    species, caseData, pressures, pressureScale)

if exist(caseData.outputDir, 'dir') ~= 7
    mkdir(caseData.outputDir);
end

kgrid = caseData.runs.noLens.kgrid;
simulationInfo = simulationNiftiInfo(caseData);

outputFiles = struct();
outputFiles.simulation.pressureWater = writeSingle( ...
    pressures.water, simulationInfo, ...
    caseData.outputDir, 'pressure_water');
outputFiles.simulation.pressureNoLens = writeSingle( ...
    pressures.noLens, simulationInfo, ...
    caseData.outputDir, 'pressure_no_lens');
outputFiles.simulation.pressureLens = writeSingle( ...
    pressures.lens, simulationInfo, ...
    caseData.outputDir, 'pressure_lens');
if species == "rat"
    outputFiles.simulation.ctHu = writeSingle( ...
        caseData.anatomyGrid.ctHu, simulationInfo, ...
        caseData.outputDir, 'ct_hu');
end
outputFiles.simulation.segmentationLabels = writeLabels( ...
    caseData.anatomyGrid.labels, simulationInfo, ...
    caseData.outputDir, 'segmentation_labels');
outputFiles.simulation.lensMask = writeMask( ...
    caseData.masks.lens, simulationInfo, ...
    caseData.outputDir, 'lens_mask');
outputFiles.simulation.deviceMask = writeMask( ...
    caseData.masks.device, simulationInfo, ...
    caseData.outputDir, 'device_mask');
outputFiles.simulation.elementMask = writeMask( ...
    caseData.masks.element, simulationInfo, ...
    caseData.outputDir, 'element_mask');
outputFiles.simulation.elementLabels = writeLabels( ...
    caseData.masks.elementLabels, simulationInfo, ...
    caseData.outputDir, 'element_labels');
outputFiles.simulation.sourceMask = writeMask( ...
    caseData.masks.source, simulationInfo, ...
    caseData.outputDir, 'source_mask');

outputFiles.native = struct();
if isfield(caseData.anatomy, 'segmentationInfo')
    [xKwaveM, yKwaveM, zKwaveM] = ...
        nativeKwaveCoordinates(caseData);
    nativeInfo = caseData.anatomy.segmentationInfo;

    nativeVolume = resampleToNative( ...
        pressures.water, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'linear');
    outputFiles.native.pressureWater = writeSingle( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'pressure_water_native');

    nativeVolume = resampleToNative( ...
        pressures.noLens, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'linear');
    outputFiles.native.pressureNoLens = writeSingle( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'pressure_no_lens_native');

    nativeVolume = resampleToNative( ...
        pressures.lens, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'linear');
    outputFiles.native.pressureLens = writeSingle( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'pressure_lens_native');

    nativeVolume = resampleToNative( ...
        caseData.masks.lens, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'nearest');
    outputFiles.native.lensMask = writeMask( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'lens_mask_native');

    nativeVolume = resampleToNative( ...
        caseData.masks.device, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'nearest');
    outputFiles.native.deviceMask = writeMask( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'device_mask_native');

    nativeVolume = resampleToNative( ...
        caseData.masks.element, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'nearest');
    outputFiles.native.elementMask = writeMask( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'element_mask_native');

    nativeVolume = resampleToNative( ...
        caseData.masks.elementLabels, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'nearest');
    outputFiles.native.elementLabels = writeLabels( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'element_labels_native');

    nativeVolume = resampleToNative( ...
        caseData.masks.source, kgrid, ...
        xKwaveM, yKwaveM, zKwaveM, 'nearest');
    outputFiles.native.sourceMask = writeMask( ...
        nativeVolume, nativeInfo, ...
        caseData.outputDir, 'source_mask_native');

    coverageMask = gridCoverage( ...
        kgrid, xKwaveM, yKwaveM, zKwaveM);
    outputFiles.native.coverageMask = writeMask( ...
        coverageMask, nativeInfo, ...
        caseData.outputDir, 'coverage_mask_native');
end

result = struct();
result.caseId = caseData.caseId;
result.caseConfig = caseData.caseConfig;
result.simulationConfig = caseData.simulationConfig;
result.pressureScale = double(pressureScale);
result.grid.size = caseData.gridGeometry.size;
result.grid.spacingM = caseData.gridGeometry.spacingM;
result.grid.geometry = caseData.gridGeometry;
result.runs.calibration = runSummary( ...
    caseData.runs.calibration);
result.runs.noLens = runSummary( ...
    caseData.runs.noLens);
result.runs.lens = runSummary( ...
    caseData.runs.lens);

result.peakPressurePa.water = double( ...
    max(pressures.water, [], 'all'));
result.peakPressurePa.noLens = double( ...
    max(pressures.noLens, [], 'all'));
result.peakPressurePa.lens = double( ...
    max(pressures.lens, [], 'all'));
result.calibratedWaterPeakPa = double(max( ...
    pressures.water(~caseData.masks.source)));

maskNames = fieldnames(caseData.masks);
for maskIndex = 1:numel(maskNames)
    maskName = maskNames{maskIndex};
    result.maskVoxelCounts.(maskName) = ...
        nnz(caseData.masks.(maskName));
end

resultFile = fullfile( ...
    caseData.outputDir, 'run_result.mat');
outputFiles.runResult = resultFile;
result.outputFiles = outputFiles;
save(resultFile, 'result');
end

function summary = runSummary(runData)

summary.gridSize = [ ...
    runData.kgrid.Nx, ...
    runData.kgrid.Ny, ...
    runData.kgrid.Nz];
summary.dt = double(runData.kgrid.dt);
summary.Nt = double(runData.kgrid.Nt);
summary.durationS = double( ...
    runData.kgrid.t_array(end));
summary.maximumSoundSpeed = double( ...
    max(runData.medium.sound_speed, [], 'all'));
end

function info = simulationNiftiInfo(caseData)

if isfield(caseData.anatomy, 'segmentationInfo')
    info = caseData.anatomy.segmentationInfo;
else
    templateBase = tempname;
    niftiwrite(zeros(1, 1, 2, 'single'), templateBase);
    templateFile = [templateBase, '.nii'];
    info = niftiinfo(templateFile);
    delete(templateFile);
end

geometry = caseData.gridGeometry;
imageSize = reshape(double(geometry.size), 1, 3);
spacingMm = 1e3 .* reshape( ...
    double(geometry.spacingM), 1, 3);
originMm = 1e3 .* reshape( ...
    double(geometry.originM), 1, 3);

worldFromKwaveM = ...
    double(geometry.worldFromKwaveM);
voxelStepMm = ...
    1e3 .* worldFromKwaveM(1:3, 1:3) * ...
    diag(double(geometry.spacingM));

info.ImageSize = imageSize;
info.PixelDimensions(1:3) = spacingMm;

if isfield(info, 'raw')
    info.raw.dim(2:4) = imageSize;
    info.raw.pixdim(2:4) = spacingMm;
    info.raw.sform_code = max( ...
        1, info.raw.sform_code);
    info.raw.srow_x = [ ...
        voxelStepMm(1, :), originMm(1)];
    info.raw.srow_y = [ ...
        voxelStepMm(2, :), originMm(2)];
    info.raw.srow_z = [ ...
        voxelStepMm(3, :), originMm(3)];
end

affineM = eye(4);
affineM(1:3, 1:3) = voxelStepMm.';
affineM(4, 1:3) = originMm;
info.TransformName = 'Sform';
info.Transform.T = affineM;
info.Filename = '';
end

function [xKwaveM, yKwaveM, zKwaveM] = ...
    nativeKwaveCoordinates(caseData)

nativeGeometry = ...
    caseData.anatomy.segmentationGeometry;
nativeSize = reshape( ...
    double(nativeGeometry.size), 1, 3);

[iNative, jNative, kNative] = ndgrid( ...
    single(1:nativeSize(1)), ...
    single(1:nativeSize(2)), ...
    single(1:nativeSize(3)));

originMm = single( ...
    1e3 * nativeGeometry.originM);
spacingMm = single( ...
    1e3 * nativeGeometry.spacingM);

xWorldM = 1e-3 .* ( ...
    originMm(1) + ...
    (iNative - 1) .* spacingMm(1));
yWorldM = 1e-3 .* ( ...
    originMm(2) + ...
    (jNative - 1) .* spacingMm(2));
zWorldM = 1e-3 .* ( ...
    originMm(3) + ...
    (kNative - 1) .* spacingMm(3));

clear iNative jNative kNative

kwaveFromWorldM = single(inv( ...
    double(caseData.gridGeometry.worldFromKwaveM)));

xKwaveM = ...
    kwaveFromWorldM(1, 1) .* xWorldM + ...
    kwaveFromWorldM(1, 2) .* yWorldM + ...
    kwaveFromWorldM(1, 3) .* zWorldM + ...
    kwaveFromWorldM(1, 4);
yKwaveM = ...
    kwaveFromWorldM(2, 1) .* xWorldM + ...
    kwaveFromWorldM(2, 2) .* yWorldM + ...
    kwaveFromWorldM(2, 3) .* zWorldM + ...
    kwaveFromWorldM(2, 4);
zKwaveM = ...
    kwaveFromWorldM(3, 1) .* xWorldM + ...
    kwaveFromWorldM(3, 2) .* yWorldM + ...
    kwaveFromWorldM(3, 3) .* zWorldM + ...
    kwaveFromWorldM(3, 4);
end

function sampled = resampleToNative( ...
    volume, kgrid, ...
    xKwaveM, yKwaveM, zKwaveM, method)

interpolant = griddedInterpolant( ...
    {double(kgrid.x_vec), ...
    double(kgrid.y_vec), ...
    double(kgrid.z_vec)}, ...
    single(volume), method, 'none');

sampled = single(interpolant( ...
    xKwaveM, yKwaveM, zKwaveM));
sampled(~isfinite(sampled)) = 0;
end

function mask = gridCoverage( ...
    kgrid, xKwaveM, yKwaveM, zKwaveM)

toleranceM = single(1e-6);
mask = ...
    xKwaveM >= single(kgrid.x_vec(1)) - toleranceM & ...
    xKwaveM <= single(kgrid.x_vec(end)) + toleranceM & ...
    yKwaveM >= single(kgrid.y_vec(1)) - toleranceM & ...
    yKwaveM <= single(kgrid.y_vec(end)) + toleranceM & ...
    zKwaveM >= single(kgrid.z_vec(1)) - toleranceM & ...
    zKwaveM <= single(kgrid.z_vec(end)) + toleranceM;
end

function outputFile = writeSingle( ...
    volume, info, outputDir, stem)

outputBase = fullfile(outputDir, stem);
info.Datatype = 'single';
info.Filename = '';
niftiwrite( ...
    single(volume), outputBase, info, ...
    'Compressed', true);
outputFile = [outputBase, '.nii.gz'];
end

function outputFile = writeMask( ...
    mask, info, outputDir, stem)

outputBase = fullfile(outputDir, stem);
info.Datatype = 'uint8';
info.BitsPerPixel = 8;
info.Filename = '';
niftiwrite( ...
    uint8(mask > 0), outputBase, info, ...
    'Compressed', true);
outputFile = [outputBase, '.nii.gz'];
end

function outputFile = writeLabels( ...
    labels, info, outputDir, stem)

outputBase = fullfile(outputDir, stem);
info.Datatype = 'uint8';
info.BitsPerPixel = 8;
info.Filename = '';
niftiwrite( ...
    uint8(labels), outputBase, info, ...
    'Compressed', true);
outputFile = [outputBase, '.nii.gz'];
end
