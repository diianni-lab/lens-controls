function signal = toneBurst( ...
    kgrid, frequencyHz, waveform)

burstDurationS = ...
    waveform.toneBurstCycles / frequencyHz;
activeIndices = find( ...
    kgrid.t_array <= burstDurationS);
activeTimeS = kgrid.t_array(activeIndices);

numberOfActiveSamples = numel(activeIndices);
windowPosition = ...
    (0:(numberOfActiveSamples - 1)).' ./ ...
    (numberOfActiveSamples - 1);

window = ones(numberOfActiveSamples, 1);
firstTaper = ...
    windowPosition < waveform.tukeyRatio / 2;
lastTaper = ...
    windowPosition >= ...
    (1 - waveform.tukeyRatio / 2);

window(firstTaper) = 0.5 .* (1 + cos( ...
    2 * pi / waveform.tukeyRatio .* ...
    (windowPosition(firstTaper) - ...
    waveform.tukeyRatio / 2)));
window(lastTaper) = 0.5 .* (1 + cos( ...
    2 * pi / waveform.tukeyRatio .* ...
    (windowPosition(lastTaper) - 1 + ...
    waveform.tukeyRatio / 2)));

signal = zeros(1, kgrid.Nt);
signal(activeIndices) = ...
    waveform.sourceAmplitudePa .* ...
    sin(2 * pi * frequencyHz .* activeTimeS) .* ...
    window.';
end
