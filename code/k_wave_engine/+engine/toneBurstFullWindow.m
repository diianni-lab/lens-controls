function signal = toneBurstFullWindow( ...
    kgrid, frequencyHz, waveform)

burstDurationS = ...
    waveform.toneBurstCycles / frequencyHz;
burstTimeS = 0:kgrid.dt:burstDurationS;
numberOfBurstSamples = numel(burstTimeS);

windowPosition = ...
    (0:(numberOfBurstSamples - 1)).' ./ ...
    (numberOfBurstSamples - 1);

window = ones(numberOfBurstSamples, 1);
firstTaper = ...
    windowPosition < waveform.tukeyRatio / 2;
lastTaper = ...
    windowPosition >= ...
    (1 - waveform.tukeyRatio / 2);

window(firstTaper) = 0.5 .* (1 + cos( ...
    2 * pi / waveform.tukeyRatio .* ...
    (windowPosition(firstTaper) - ...
    waveform.tukeyRatio / 2)));
window(lastTaper) = 0.5 .* (1 + cos( ...
    2 * pi / waveform.tukeyRatio .* ...
    (windowPosition(lastTaper) - 1 + ...
    waveform.tukeyRatio / 2)));

burstSignal = ...
    waveform.sourceAmplitudePa .* ...
    sin(2 * pi * frequencyHz .* burstTimeS) .* ...
    window.';

signal = zeros(1, kgrid.Nt);
numberOfCopiedSamples = min( ...
    numberOfBurstSamples, kgrid.Nt);
signal(1:numberOfCopiedSamples) = ...
    burstSignal(1:numberOfCopiedSamples);
end
