function result = runCase(species, simulationConfig, caseConfig)

buildCase = str2func(species + ".buildCase");
caseData = buildCase(simulationConfig, caseConfig);

[pressureScale, calibratedWaterPressure] = ...
    engine.calibrateSource(caseData, simulationConfig);

noLensPressure = engine.runSolver( ...
    caseData, ...
    "noLens", ...
    simulationConfig, ...
    pressureScale);

lensPressure = engine.runSolver( ...
    caseData, ...
    "lens", ...
    simulationConfig, ...
    pressureScale * ...
    (1 + simulationConfig.lens.amplitudeCorrection));

pressures = struct();
pressures.water = calibratedWaterPressure;
pressures.noLens = noLensPressure;
pressures.lens = lensPressure;

result = engine.writeOutputs( ...
    species, caseData, pressures, pressureScale);
end
