function pressure = runSolver( ...
    caseData, runName, simulationConfig, sourceScale)

runData = caseData.runs.(char(runName));

source = runData.source;
source.p = single(sourceScale) .* source.p;

inputArgs = { ...
    'PMLSize', simulationConfig.solver.pmlSize, ...
    'PMLInside', false, ...
    'PlotPML', false, ...
    'PlotSim', false, ...
    'DisplayMask', 'off'};

switch char(simulationConfig.backend)
    case 'matlab-gpu'
        sensorData = kspaceFirstOrder3D( ...
            runData.kgrid, ...
            runData.medium, ...
            source, ...
            runData.sensor, ...
            inputArgs{:}, ...
            'DataCast', 'gpuArray-single');

    case 'cuda'
        dataPath = char(fullfile( ...
            caseData.outputDir, 'kwave_tmp'));
        mkdir(dataPath);

        sensorData = kspaceFirstOrder3DG( ...
            runData.kgrid, ...
            runData.medium, ...
            source, ...
            runData.sensor, ...
            inputArgs{:}, ...
            'DataPath', dataPath, ...
            'DeleteData', true);
end

pMin = sensorData.p_min_all;
if isa(pMin, 'gpuArray')
    pMin = gather(pMin);
end

pressure = single(-reshape( ...
    pMin, ...
    runData.kgrid.Nx, ...
    runData.kgrid.Ny, ...
    runData.kgrid.Nz));
end
