function [pressureScale, calibratedPressure] = ...
    calibrateSource(caseData, simulationConfig)

waterPressure = engine.runSolver( ...
    caseData, ...
    "calibration", ...
    simulationConfig, ...
    1);

waterPeak = max(waterPressure( ...
    ~caseData.runs.calibration.source.p_mask));
pressureScale = ...
    simulationConfig.calibration.targetPressurePa / waterPeak;

calibratedPressure = single(pressureScale) .* waterPressure;

fprintf( ...
    'Water peak: %.6g Pa, target: %.6g Pa, scale: %.9g\n', ...
    waterPeak, ...
    simulationConfig.calibration.targetPressurePa, ...
    pressureScale);
end
