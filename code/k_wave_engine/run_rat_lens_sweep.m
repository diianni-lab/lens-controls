function run_rat_lens_sweep(outputRoot)

engineRoot = fileparts(mfilename('fullpath'));
configRoot = fullfile( ...
    engineRoot, 'configs', 'rat', 'lens_sweep');

simulationConfig = jsondecode(fileread( ...
    fullfile(configRoot, 'simulation.json')));
sweepConfig = jsondecode(fileread( ...
    fullfile(configRoot, 'sweep.json')));

gridSize = reshape( ...
    double(simulationConfig.grid.size), 1, 3);
gridSpacingM = simulationConfig.grid.spacingM;

noLensGrid = kWaveGrid( ...
    gridSize(1), gridSpacingM, ...
    gridSize(2), gridSpacingM, ...
    gridSize(3), gridSpacingM);
lensGrid = kWaveGrid( ...
    gridSize(1), gridSpacingM, ...
    gridSize(2), gridSpacingM, ...
    gridSize(3), gridSpacingM);

water = waterMedium(gridSize, simulationConfig);
setSimulationTime( ...
    noLensGrid, water, simulationConfig);

initialConfig = simulationConfig;
initialConfig.lens.maximumThicknessM = ...
    1e-3 * sweepConfig.nominalThicknessMm(1);
initialConfig.lens.pillarWidthMm = ...
    sweepConfig.pillarWidthMm(1);
initialConfig.lens.seed = sweepConfig.referenceSeed;

initialMasks = rat.buildLens( ...
    lensGrid, initialConfig);
initialLensMedium = lensMedium( ...
    water, initialMasks.lens, initialConfig);
setSimulationTime( ...
    lensGrid, initialLensMedium, simulationConfig);

noLensSource = rat.buildSource( ...
    noLensGrid, initialMasks.device, simulationConfig);
noLensSource.p = single(engine.toneBurstFullWindow( ...
    noLensGrid, ...
    simulationConfig.frequencyHz, ...
    simulationConfig.waveform));

lensSource = rat.buildSource( ...
    lensGrid, initialMasks.device, simulationConfig);
lensSource.p = single(engine.toneBurstFullWindow( ...
    lensGrid, ...
    simulationConfig.frequencyHz, ...
    simulationConfig.waveform));

sensor = struct();
sensor.mask = true(gridSize);
sensor.record = {'p_min_all'};

niftiInfo = gridNiftiInfo(lensGrid);

noLensDir = fullfile(outputRoot, 'no_lens');
flatDir = fullfile(outputRoot, 'flat_lens');
pillaredDir = fullfile(outputRoot, 'pillared_lens');
calibrationDir = fullfile(outputRoot, 'calibration');
mkdir(outputRoot);
mkdir(noLensDir);
mkdir(flatDir);
mkdir(pillaredDir);
mkdir(calibrationDir);

noLensPressure = runPressure( ...
    noLensGrid, water, noLensSource, sensor, ...
    simulationConfig, noLensDir, 1);
writeGridNifti( ...
    noLensPressure, niftiInfo, ...
    fullfile(noLensDir, 'pressure'));
writeGridNifti( ...
    initialMasks.device, niftiInfo, ...
    fullfile(outputRoot, 'transducer_mask'));

focalMask = noLensPressure >= ...
    max(noLensPressure, [], 'all') * 10 ^ (-6 / 20);
noLensAverage = mean(noLensPressure(focalMask));
writeGridNifti( ...
    focalMask, niftiInfo, ...
    fullfile(noLensDir, 'focal_volume_6db'));

nominalThicknessMm = ...
    sweepConfig.nominalThicknessMm(:);
pillarWidthMm = ...
    sweepConfig.pillarWidthMm(:);

numberOfThicknesses = numel(nominalThicknessMm);
numberOfPillarWidths = numel(pillarWidthMm);
meanThicknessMm = zeros( ...
    numberOfThicknesses, numberOfPillarWidths);

for pillarIndex = 1:numberOfPillarWidths
    for thicknessIndex = 1:numberOfThicknesses
        referenceConfig = simulationConfig;
        referenceConfig.lens.maximumThicknessM = ...
            1e-3 * nominalThicknessMm(thicknessIndex);
        referenceConfig.lens.pillarWidthMm = ...
            pillarWidthMm(pillarIndex);
        referenceConfig.lens.seed = ...
            sweepConfig.referenceSeed;

        [~, lensInfo] = rat.buildLens( ...
            lensGrid, referenceConfig);
        meanThicknessMm(thicknessIndex, pillarIndex) = ...
            double(lensInfo.meanThicknessM * 1e3);
    end
end

uniformThicknessMm = mean(meanThicknessMm, 2);

referenceThickness = table( ...
    repmat( ...
    sweepConfig.referenceSeed, ...
    numberOfThicknesses * numberOfPillarWidths, 1), ...
    repelem(pillarWidthMm, numberOfThicknesses), ...
    repmat(nominalThicknessMm, numberOfPillarWidths, 1), ...
    meanThicknessMm(:), ...
    'VariableNames', { ...
    'seed', ...
    'pillar_width_mm', ...
    'nominal_thickness_mm', ...
    'mean_thickness_mm'});
writetable( ...
    referenceThickness, ...
    fullfile(calibrationDir, ...
    'reference_lens_thicknesses.csv'));

equivalentThickness = table( ...
    nominalThicknessMm, uniformThicknessMm, ...
    'VariableNames', { ...
    'nominal_thickness_mm', ...
    'uniform_thickness_mm'});
writetable( ...
    equivalentThickness, ...
    fullfile(calibrationDir, ...
    'equivalent_uniform_thicknesses.csv'));

uniformAveragePa = zeros(numberOfThicknesses, 1);
uniformPeakPa = zeros(numberOfThicknesses, 1);

for thicknessIndex = 1:numberOfThicknesses
    uniformMm = uniformThicknessMm(thicknessIndex);

    uniformConfig = simulationConfig;
    uniformConfig.lens.baseThicknessM = ...
        1e-3 * uniformMm;
    uniformConfig.lens.maximumThicknessM = ...
        1e-3 * uniformMm;
    uniformConfig.lens.pillarWidthMm = 1;
    uniformConfig.lens.seed = ...
        sweepConfig.referenceSeed;

    masks = rat.buildLens(lensGrid, uniformConfig);
    medium = lensMedium( ...
        water, masks.lens, uniformConfig);

    pressure = runPressure( ...
        lensGrid, medium, lensSource, sensor, ...
        simulationConfig, flatDir, 1);

    thicknessTag = numberTag(uniformMm);
    writeGridNifti( ...
        pressure, niftiInfo, ...
        fullfile(flatDir, ...
        ['pressure_uncorrected_th', ...
        thicknessTag, 'mm']));
    writeGridNifti( ...
        masks.lens, niftiInfo, ...
        fullfile(flatDir, ...
        ['lens_mask_th', thicknessTag, 'mm']));

    uniformAveragePa(thicknessIndex) = ...
        mean(pressure(focalMask));
    uniformPeakPa(thicknessIndex) = ...
        max(pressure, [], 'all');

    fprintf( ...
        'Uncorrected flat lens %d/%d: %.6g mm\n', ...
        thicknessIndex, numberOfThicknesses, uniformMm);
end

sourceAmplitudeScale = ...
    noLensAverage ./ uniformAveragePa;

correctionRatios = table( ...
    nominalThicknessMm, ...
    uniformThicknessMm, ...
    sourceAmplitudeScale, ...
    repmat(noLensAverage, numberOfThicknesses, 1), ...
    uniformAveragePa, ...
    uniformPeakPa, ...
    'VariableNames', { ...
    'nominal_thickness_mm', ...
    'uniform_thickness_mm', ...
    'source_amplitude_scale', ...
    'no_lens_average_pa', ...
    'uniform_average_pa', ...
    'uniform_peak_pa'});
writetable( ...
    correctionRatios, ...
    fullfile(calibrationDir, ...
    'source_amplitude_corrections.csv'));

for thicknessIndex = 1:numberOfThicknesses
    uniformMm = uniformThicknessMm(thicknessIndex);

    uniformConfig = simulationConfig;
    uniformConfig.lens.baseThicknessM = ...
        1e-3 * uniformMm;
    uniformConfig.lens.maximumThicknessM = ...
        1e-3 * uniformMm;
    uniformConfig.lens.pillarWidthMm = 1;
    uniformConfig.lens.seed = ...
        sweepConfig.referenceSeed;

    masks = rat.buildLens(lensGrid, uniformConfig);
    medium = lensMedium( ...
        water, masks.lens, uniformConfig);
    correctedPressure = runPressure( ...
        lensGrid, medium, lensSource, sensor, ...
        simulationConfig, flatDir, ...
        sourceAmplitudeScale(thicknessIndex));

    thicknessTag = numberTag(uniformMm);
    writeGridNifti( ...
        correctedPressure, niftiInfo, ...
        fullfile(flatDir, ...
        ['pressure_corrected_th', ...
        thicknessTag, 'mm']));

    fprintf( ...
        'Corrected flat lens %d/%d: %.6g mm\n', ...
        thicknessIndex, numberOfThicknesses, uniformMm);
end

[thicknessIndex, pillarIndex, seedIndex] = ndgrid( ...
    1:numel(sweepConfig.nominalThicknessMm), ...
    1:numel(sweepConfig.pillarWidthMm), ...
    1:numel(sweepConfig.seeds));

combinationList = [ ...
    sweepConfig.seeds(seedIndex(:)), ...
    sweepConfig.pillarWidthMm(pillarIndex(:)), ...
    sweepConfig.nominalThicknessMm(thicknessIndex(:)), ...
    thicknessIndex(:)];
numberOfCombinations = size(combinationList, 1);

for seed = reshape(sweepConfig.seeds, 1, [])
    mkdir(fullfile( ...
        pillaredDir, sprintf('seed_%02d', seed)));
end

pool = gcp('nocreate');
if isempty(pool)
    parpool('local', sweepConfig.workers);
end

parfor combinationIndex = 1:numberOfCombinations
    seed = combinationList(combinationIndex, 1);
    pillarWidthMm = combinationList(combinationIndex, 2);
    thicknessMm = combinationList(combinationIndex, 3);
    scaleIndex = combinationList(combinationIndex, 4);

    combinationConfig = simulationConfig;
    combinationConfig.lens.maximumThicknessM = ...
        1e-3 * thicknessMm;
    combinationConfig.lens.pillarWidthMm = ...
        pillarWidthMm;
    combinationConfig.lens.seed = seed;

    masks = rat.buildLens( ...
        lensGrid, combinationConfig);
    medium = lensMedium( ...
        water, masks.lens, combinationConfig);
    pressure = runPressure( ...
        lensGrid, medium, lensSource, sensor, ...
        simulationConfig, pillaredDir, ...
        sourceAmplitudeScale(scaleIndex));

    seedDir = fullfile( ...
        pillaredDir, sprintf('seed_%02d', seed));
    suffix = sprintf( ...
        '_pw%smm_th%smm', ...
        numberTag(pillarWidthMm), ...
        numberTag(thicknessMm));

    writeGridNifti( ...
        pressure, niftiInfo, ...
        fullfile(seedDir, ...
        ['pressure_corrected', suffix]));
    writeGridNifti( ...
        masks.lens, niftiInfo, ...
        fullfile(seedDir, ...
        ['lens_mask', suffix]));

    fprintf( ...
        'Pillared lens %d/%d: seed=%d, pw=%.2f, th=%.2f\n', ...
        combinationIndex, numberOfCombinations, ...
        seed, pillarWidthMm, thicknessMm);
end
end

function medium = waterMedium(gridSize, simulationConfig)

medium.sound_speed = ...
    single(simulationConfig.medium.soundSpeed) .* ...
    ones(gridSize, 'single');
medium.density = ...
    single(simulationConfig.medium.density) .* ...
    ones(gridSize, 'single');
medium.alpha_coeff = ...
    single(simulationConfig.medium.alphaCoeff) .* ...
    ones(gridSize, 'single');
medium.alpha_power = ...
    simulationConfig.medium.alphaPower;
end

function medium = lensMedium( ...
    water, lensMask, simulationConfig)

medium = water;
medium.sound_speed(lensMask) = ...
    simulationConfig.lens.soundSpeed;
medium.density(lensMask) = ...
    simulationConfig.lens.density;
medium.alpha_coeff(lensMask) = ...
    simulationConfig.lens.alphaCoeff;
end

function setSimulationTime( ...
    kgrid, medium, simulationConfig)

maximumSoundSpeed = ...
    max(medium.sound_speed, [], 'all');
timeStepS = ...
    simulationConfig.solver.cfl * ...
    kgrid.dx / maximumSoundSpeed;
numberOfTimeSteps = floor( ...
    simulationConfig.solver.durationS / ...
    timeStepS) + 1;
kgrid.setTime(numberOfTimeSteps, timeStepS);
end

function pressure = runPressure( ...
    kgrid, medium, source, sensor, ...
    simulationConfig, outputDir, sourceScale)

runData.kgrid = kgrid;
runData.medium = medium;
runData.source = source;
runData.sensor = sensor;

caseData.outputDir = outputDir;
caseData.runs.simulation = runData;

pressure = engine.runSolver( ...
    caseData, "simulation", ...
    simulationConfig, sourceScale);
end

function info = gridNiftiInfo(kgrid)

templateBase = tempname;
niftiwrite(zeros(1, 1, 2, 'single'), templateBase);
templateFile = [templateBase, '.nii'];
info = niftiinfo(templateFile);
delete(templateFile);

imageSize = [kgrid.Nx, kgrid.Ny, kgrid.Nz];
spacingMm = 1e3 .* [kgrid.dx, kgrid.dy, kgrid.dz];
originMm = 1e3 .* [ ...
    kgrid.x_vec(1), ...
    kgrid.y_vec(1), ...
    kgrid.z_vec(1)];

info.ImageSize = imageSize;
info.PixelDimensions(1:3) = spacingMm;
info.raw.dim(2:4) = imageSize;
info.raw.pixdim(2:4) = spacingMm;
info.raw.sform_code = max(1, info.raw.sform_code);
info.raw.srow_x = [spacingMm(1), 0, 0, originMm(1)];
info.raw.srow_y = [0, spacingMm(2), 0, originMm(2)];
info.raw.srow_z = [0, 0, spacingMm(3), originMm(3)];

transform = eye(4);
transform(1:3, 1:3) = diag(spacingMm);
transform(4, 1:3) = originMm;
info.TransformName = 'Sform';
info.Transform.T = transform;
info.Filename = '';
end

function writeGridNifti(volume, info, outputBase)

if islogical(volume) || isa(volume, 'uint8')
    volume = uint8(volume > 0);
    info.Datatype = 'uint8';
    info.BitsPerPixel = 8;
else
    volume = single(volume);
    info.Datatype = 'single';
    info.BitsPerPixel = 32;
end

niftiwrite( ...
    volume, outputBase, info, ...
    'Compressed', true);
end

function tag = numberTag(value)

tag = strrep(sprintf('%.2f', value), '.', 'p');
end
