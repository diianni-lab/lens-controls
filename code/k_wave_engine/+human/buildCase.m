function caseData = buildCase( ...
    simulationConfig, caseConfig)

anatomy = human.loadAnatomy(caseConfig);

[kgrid, gridGeometry, localToWorldM, ...
    localToKwaveM] = simulationGrid( ...
    anatomy, simulationConfig, caseConfig);

labels = engine.resampleVolume( ...
    anatomy.labels, ...
    anatomy.segmentationGeometry, ...
    kgrid, gridGeometry, ...
    'nearest', 0);
labels = round(labels);

ctHu = engine.resampleVolume( ...
    anatomy.ctHu, ...
    anatomy.ctGeometry, ...
    kgrid, gridGeometry, ...
    'linear', ...
    min(simulationConfig.medium.skull.ctCalibrationHU));

anatomy.labels = [];
anatomy.ctHu = [];

masks = human.buildLens( ...
    kgrid, localToKwaveM, simulationConfig);

media = human.buildMedium( ...
    labels, ctHu, masks.lens, simulationConfig);

setSimulationTime(kgrid, media, simulationConfig);

source = human.buildSource( ...
    kgrid, localToKwaveM, ...
    simulationConfig, caseConfig);
masks.source = source.p_mask;

sensor = struct();
sensor.mask = true( ...
    kgrid.Nx, kgrid.Ny, kgrid.Nz);
sensor.record = {'p_min_all'};

caseData = struct();
caseData.caseId = caseConfig.caseId;
caseData.outputDir = caseConfig.outputDir;
caseData.caseConfig = caseConfig;
caseData.simulationConfig = simulationConfig;
caseData.anatomy = anatomy;
caseData.anatomyGrid.labels = labels;
caseData.gridGeometry = gridGeometry;
caseData.localToWorldM = localToWorldM;
caseData.localToKwaveM = localToKwaveM;
caseData.masks = masks;
caseData.runs.calibration = simulationRun( ...
    kgrid, media.calibration, source, sensor);
caseData.runs.noLens = simulationRun( ...
    kgrid, media.noLens, source, sensor);
caseData.runs.lens = simulationRun( ...
    kgrid, media.lens, source, sensor);
end

function runData = simulationRun( ...
    kgrid, medium, source, sensor)

runData = struct();
runData.kgrid = kgrid;
runData.medium = medium;
runData.source = source;
runData.sensor = sensor;
end

function [kgrid, geometry, localToWorldM, ...
    localToKwaveM] = simulationGrid( ...
    anatomy, simulationConfig, caseConfig)

gridConfig = simulationConfig.grid;
spacingM = gridConfig.spacingM;

gridSize = [ ...
    2 * ceil(gridConfig.lateralM / spacingM) + 1, ...
    2 * ceil(gridConfig.lateralM / spacingM) + 1, ...
    ceil((gridConfig.behindTransducerM + ...
        gridConfig.inFrontOfTransducerM) / spacingM) + 1];

kgrid = kWaveGrid( ...
    gridSize(1), spacingM, ...
    gridSize(2), spacingM, ...
    gridSize(3), spacingM);

localToWorldM = transducerPose( ...
    anatomy, caseConfig);

localMidpointM = [ ...
    0; ...
    0; ...
    (gridConfig.behindTransducerM - ...
        gridConfig.inFrontOfTransducerM) / 2];

worldFromKwaveM = localToWorldM;
worldFromKwaveM(1:3, 4) = ...
    localToWorldM(1:3, 4) + ...
    localToWorldM(1:3, 1:3) * localMidpointM;

localToKwaveM = ...
    worldFromKwaveM \ localToWorldM;

firstWorldM = worldFromKwaveM * [ ...
    kgrid.x_vec(1); ...
    kgrid.y_vec(1); ...
    kgrid.z_vec(1); ...
    1];

geometry.size = gridSize;
geometry.spacingM = ...
    [spacingM, spacingM, spacingM];
geometry.originM = firstWorldM(1:3).';
geometry.worldFromKwaveM = worldFromKwaveM;
end

function transformM = transducerPose( ...
    anatomy, caseConfig)

poseFile = fullfile( ...
    caseConfig.dataRoot, caseConfig.poseFile);

lines = strip(readlines(poseFile));
poseRow = lines( ...
    strlength(lines) > 0 & ...
    ~startsWith(lines, "#"));

parts = split(poseRow, char(9));
values = str2double(parts(2:13));

locationMm = values(1:3);
rotationBrainsight = ...
    reshape(values(4:12), 3, 3).';

originMm = ...
    1e3 * anatomy.ctGeometry.originM(:);
spacingMm = ...
    1e3 * anatomy.ctGeometry.spacingM(:);
extentMm = originMm + ...
    (anatomy.ctGeometry.size(:) - 1) .* spacingMm;

translationMm = [ ...
    extentMm(1) - locationMm(1); ...
    extentMm(2) - locationMm(2); ...
    originMm(3) + locationMm(3)];

transformM = eye(4);
transformM(1:3, 1:3) = ...
    (rotationBrainsight * diag([-1, -1, 1])).';
transformM(1:3, 4) = 1e-3 * translationMm;
end

function setSimulationTime( ...
    kgrid, media, simulationConfig)

maximumSoundSpeed = max([ ...
    max(media.calibration.sound_speed, [], 'all'), ...
    max(media.noLens.sound_speed, [], 'all'), ...
    max(media.lens.sound_speed, [], 'all')]);

timeStepS = ...
    simulationConfig.solver.cfl * kgrid.dx / ...
    maximumSoundSpeed;

domainSizeM = [ ...
    kgrid.Nx * kgrid.dx, ...
    kgrid.Ny * kgrid.dy, ...
    kgrid.Nz * kgrid.dz];

durationS = ...
    simulationConfig.grid.traversals * ...
    norm(domainSizeM) / ...
    simulationConfig.medium.background.soundSpeed;

numberOfTimeSteps = ceil(durationS / timeStepS) + 1;
kgrid.setTime(numberOfTimeSteps, timeStepS);
end
