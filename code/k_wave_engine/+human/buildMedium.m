function media = buildMedium( ...
    labels, ctHu, lensMask, simulationConfig)

mediumConfig = simulationConfig.medium;
frequencyMHz = simulationConfig.frequencyHz * 1e-6;
alphaPower = mediumConfig.solverAlphaPower;

brainMask = labels == 1;
skullMask = labels == 2;

noLens = struct();
noLens.sound_speed = ...
    single(mediumConfig.background.soundSpeed) .* ...
    ones(size(labels), 'single');
noLens.density = ...
    single(mediumConfig.background.density) .* ...
    ones(size(labels), 'single');
noLens.alpha_coeff = ...
    single(effectiveAlpha( ...
        mediumConfig.background, ...
        frequencyMHz, alphaPower)) .* ...
    ones(size(labels), 'single');
noLens.alpha_power = alphaPower;

noLens.sound_speed(brainMask) = ...
    mediumConfig.softTissue.soundSpeed;
noLens.density(brainMask) = ...
    mediumConfig.softTissue.density;
noLens.alpha_coeff(brainMask) = ...
    effectiveAlpha( ...
        mediumConfig.softTissue, ...
        frequencyMHz, alphaPower);

skullConfig = mediumConfig.skull;
skullHu = double(ctHu(skullMask));
skullDensity = interp1( ...
    skullConfig.ctCalibrationHU, ...
    skullConfig.ctCalibrationDensity, ...
    skullHu, 'linear', 'extrap');

noLens.density(skullMask) = single(skullDensity);
noLens.sound_speed(skullMask) = single( ...
    skullConfig.soundSpeedDensitySlope .* ...
    skullDensity + ...
    skullConfig.soundSpeedIntercept);
noLens.alpha_coeff(skullMask) = ...
    effectiveAlpha( ...
        skullConfig, frequencyMHz, alphaPower);

lens = noLens;
lensConfig = simulationConfig.lens;
lens.sound_speed(lensMask) = ...
    lensConfig.soundSpeed;
lens.density(lensMask) = ...
    lensConfig.density;
lens.alpha_coeff(lensMask) = ...
    effectiveAlpha( ...
        lensConfig, frequencyMHz, alphaPower);

calibrationConfig = ...
    simulationConfig.calibration.medium;
calibration = struct();
calibration.sound_speed = ...
    single(calibrationConfig.soundSpeed);
calibration.density = ...
    single(calibrationConfig.density);
calibration.alpha_coeff = single( ...
    effectiveAlpha( ...
        calibrationConfig, ...
        frequencyMHz, alphaPower));
calibration.alpha_power = alphaPower;

media = struct();
media.calibration = calibration;
media.noLens = noLens;
media.lens = lens;
end

function coefficient = effectiveAlpha( ...
    material, frequencyMHz, outputPower)

coefficient = ...
    material.alphaCoeff .* ...
    frequencyMHz .^ material.alphaPower ./ ...
    frequencyMHz .^ outputPower;
end
