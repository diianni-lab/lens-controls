function source = buildSource( ...
    kgrid, localToKwaveM, ...
    simulationConfig, caseConfig)

transducer = simulationConfig.transducer;

karray = kWaveArray( ...
    'BLITolerance', ...
    transducer.bliTolerance, ...
    'UpsamplingRate', ...
    transducer.upsamplingRate, ...
    'SinglePrecision', ...
    transducer.singlePrecision);

karray.addAnnularArray( ...
    [0, 0, 0], ...
    transducer.radiusOfCurvatureM, ...
    transducer.annularDiametersM, ...
    [0, 0, -1]);
karray.setAffineTransform(localToKwaveM);

focalDistanceM = ...
    caseConfig.focalDistanceM + ...
    transducer.focalDistanceSurfaceOffsetM;

elementSignal = engine.toneBurst( ...
    kgrid, ...
    simulationConfig.frequencyHz, ...
    simulationConfig.waveform);
numberOfElements = size( ...
    transducer.annularDiametersM, 2);
elementSignals = repmat( ...
    elementSignal, numberOfElements, 1);

elementSignals = applyElementDelays( ...
    elementSignals, ...
    kgrid.dt, ...
    focalDistanceM, ...
    simulationConfig);

source = struct();
source.p_mask = ...
    karray.getArrayBinaryMask(kgrid);
source.p = ...
    karray.getDistributedSourceSignal( ...
        kgrid, elementSignals);
end

function delayedSignals = applyElementDelays( ...
    signals, timeStepS, ...
    focalDistanceM, simulationConfig)

transducer = simulationConfig.transducer;
diametersM = transducer.annularDiametersM;

ringRadiiM = mean(diametersM, 1) / 2;
ringDepthsM = ...
    transducer.radiusOfCurvatureM - sqrt( ...
    transducer.radiusOfCurvatureM ^ 2 - ...
    ringRadiiM .^ 2);

pathLengthsM = sqrt( ...
    ringRadiiM .^ 2 + ...
    (focalDistanceM - ringDepthsM) .^ 2);

delaysS = ...
    (pathLengthsM - min(pathLengthsM)) ./ ...
    simulationConfig.medium.background.soundSpeed;

sampleShifts = round( ...
    (max(delaysS) - delaysS) ./ timeStepS);

delayedSignals = zeros(size(signals));
for elementIndex = 1:size(signals, 1)
    shift = sampleShifts(elementIndex);
    delayedSignals( ...
        elementIndex, (shift + 1):end) = ...
        signals( ...
        elementIndex, 1:(end - shift));
end
end
