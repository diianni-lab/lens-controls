function masks = buildLens( ...
    kgrid, localToKwaveM, simulationConfig)

[localX, localY, localZ] = ...
    localCoordinates(kgrid, localToKwaveM);

transducer = simulationConfig.transducer;
radialDistanceSquared = localX .^ 2 + localY .^ 2;

deviceBoundsM = transducer.deviceZBoundsM;
masks.device = ...
    radialDistanceSquared <= ...
    single(transducer.deviceRadiusM ^ 2) & ...
    localZ >= single(deviceBoundsM(1)) & ...
    localZ <= single(deviceBoundsM(2));

elementBoundsM = transducer.elementZBoundsM;
elementPlane = ...
    localZ >= single(elementBoundsM(1)) & ...
    localZ <= single(elementBoundsM(2));

diametersM = transducer.annularDiametersM;
masks.elementLabels = zeros( ...
    kgrid.Nx, kgrid.Ny, kgrid.Nz, 'uint8');

for elementIndex = 1:size(diametersM, 2)
    innerRadiusM = ...
        diametersM(1, elementIndex) / 2;
    outerRadiusM = ...
        diametersM(2, elementIndex) / 2;

    elementMask = ...
        elementPlane & ...
        radialDistanceSquared >= ...
        single(innerRadiusM ^ 2) & ...
        radialDistanceSquared <= ...
        single(outerRadiusM ^ 2);

    masks.elementLabels(elementMask) = ...
        uint8(elementIndex);
end

masks.element = masks.elementLabels > 0;

lensConfig = simulationConfig.lens;
lensRadiusM = max(diametersM(2, :)) / 2;
lensFootprint = ...
    radialDistanceSquared <= single(lensRadiusM ^ 2);
footprintIndices = find(lensFootprint);

pillarValues = lensPillarValues( ...
    localX, localY, ...
    footprintIndices, lensConfig);

thicknessM = ...
    single(lensConfig.baseThicknessM) + ...
    single(lensConfig.maximumThicknessM - ...
        lensConfig.baseThicknessM) .* ...
    pillarValues;

lensTallestPillarM = ...
    deviceBoundsM(1) - lensConfig.distanceM;
lensFocusSideM = ...
    lensTallestPillarM - double(max(thicknessM));

lensZ = localZ(footprintIndices);
masks.lens = false( ...
    kgrid.Nx, kgrid.Ny, kgrid.Nz);
masks.lens(footprintIndices) = ...
    lensZ >= single(lensFocusSideM) & ...
    lensZ <= single(lensFocusSideM) + thicknessM;
end

function [localX, localY, localZ] = ...
    localCoordinates(kgrid, localToKwaveM)

[xKwaveM, yKwaveM, zKwaveM] = ndgrid( ...
    single(kgrid.x_vec), ...
    single(kgrid.y_vec), ...
    single(kgrid.z_vec));

kwaveToLocalM = inv(localToKwaveM);

localX = ...
    single(kwaveToLocalM(1, 1)) .* xKwaveM + ...
    single(kwaveToLocalM(1, 2)) .* yKwaveM + ...
    single(kwaveToLocalM(1, 3)) .* zKwaveM + ...
    single(kwaveToLocalM(1, 4));
localY = ...
    single(kwaveToLocalM(2, 1)) .* xKwaveM + ...
    single(kwaveToLocalM(2, 2)) .* yKwaveM + ...
    single(kwaveToLocalM(2, 3)) .* zKwaveM + ...
    single(kwaveToLocalM(2, 4));
localZ = ...
    single(kwaveToLocalM(3, 1)) .* xKwaveM + ...
    single(kwaveToLocalM(3, 2)) .* yKwaveM + ...
    single(kwaveToLocalM(3, 3)) .* zKwaveM + ...
    single(kwaveToLocalM(3, 4));

clear xKwaveM yKwaveM zKwaveM
end

function values = lensPillarValues( ...
    localX, localY, footprintIndices, lensConfig)

mapSize = lensConfig.pillarMapSamplesPerAxis;
mapSpacingM = lensConfig.pillarMapSpacingM;

granularity = ...
    lensConfig.pillarWidthMm / ...
    (1e3 * mapSpacingM);
numberOfPillars = ceil(mapSize / granularity);

rng(lensConfig.seed);
smallMap = rand( ...
    numberOfPillars, numberOfPillars);

[smallX, smallY] = meshgrid( ...
    1:numberOfPillars, ...
    1:numberOfPillars);

fullAxis = linspace( ...
    1, numberOfPillars, mapSize);
[fullX, fullY] = meshgrid( ...
    fullAxis, fullAxis);

pillarMap = interp2( ...
    smallX, smallY, smallMap.', ...
    fullX, fullY, 'nearest').';
pillarMap = single(pillarMap);

mapCenter = (mapSize + 1) / 2;
mapX = round( ...
    double(localX(footprintIndices)) / ...
    mapSpacingM + mapCenter);
mapY = round( ...
    double(localY(footprintIndices)) / ...
    mapSpacingM + mapCenter);

values = pillarMap(sub2ind( ...
    [mapSize, mapSize], mapX, mapY));
end
