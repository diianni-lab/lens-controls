function caseData = buildCase( ...
    simulationConfig, caseConfig)

anatomy = rat.loadAnatomy(caseConfig);

[noLensGrid, lensGrid, gridGeometry] = ...
    simulationGrids(simulationConfig, caseConfig);

labels = engine.resampleVolume( ...
    anatomy.labels, ...
    anatomy.segmentationGeometry, ...
    noLensGrid, gridGeometry, ...
    'nearest', 0);
labels = round(labels);

ctHu = engine.resampleVolume( ...
    anatomy.ctHu, ...
    anatomy.ctGeometry, ...
    noLensGrid, gridGeometry, ...
    'linear', -990);

anatomy.labels = [];
anatomy.ctHu = [];

masks = rat.buildLens( ...
    noLensGrid, simulationConfig);

media = rat.buildMedium( ...
    labels, masks.lens, simulationConfig);

setSimulationTime( ...
    noLensGrid, media.noLens, simulationConfig);
setSimulationTime( ...
    lensGrid, media.lens, simulationConfig);

noLensSource = rat.buildSource( ...
    noLensGrid, masks.device, simulationConfig);
lensSource = rat.buildSource( ...
    lensGrid, masks.device, simulationConfig);

masks.source = noLensSource.p_mask;

sensor = struct();
sensor.mask = true( ...
    noLensGrid.Nx, ...
    noLensGrid.Ny, ...
    noLensGrid.Nz);
sensor.record = {'p_min_all'};

caseData = struct();
caseData.caseId = caseConfig.caseId;
caseData.outputDir = caseConfig.outputDir;
caseData.caseConfig = caseConfig;
caseData.simulationConfig = simulationConfig;
caseData.anatomy = anatomy;
caseData.anatomyGrid.ctHu = ctHu;
caseData.anatomyGrid.labels = labels;
caseData.gridGeometry = gridGeometry;
caseData.masks = masks;
caseData.runs.calibration = simulationRun( ...
    noLensGrid, ...
    media.calibration, ...
    noLensSource, sensor);
caseData.runs.noLens = simulationRun( ...
    noLensGrid, ...
    media.noLens, ...
    noLensSource, sensor);
caseData.runs.lens = simulationRun( ...
    lensGrid, ...
    media.lens, ...
    lensSource, sensor);
end

function runData = simulationRun( ...
    kgrid, medium, source, sensor)

runData = struct();
runData.kgrid = kgrid;
runData.medium = medium;
runData.source = source;
runData.sensor = sensor;
end

function [noLensGrid, lensGrid, geometry] = ...
    simulationGrids(simulationConfig, caseConfig)

gridSize = reshape( ...
    double(simulationConfig.grid.size), 1, 3);
spacingM = simulationConfig.grid.spacingM;

noLensGrid = kWaveGrid( ...
    gridSize(1), spacingM, ...
    gridSize(2), spacingM, ...
    gridSize(3), spacingM);
lensGrid = kWaveGrid( ...
    gridSize(1), spacingM, ...
    gridSize(2), spacingM, ...
    gridSize(3), spacingM);

targetAtlasM = 1e-3 .* [ ...
    caseConfig.targetAtlasMm.dv; ...
    caseConfig.targetAtlasMm.ml; ...
    caseConfig.targetAtlasMm.ap];

sourceAtlasM = targetAtlasM - [ ...
    simulationConfig.transducer ...
    .sourceToTargetDistanceM; ...
    0; ...
    0];

sourceIndex = round([ ...
    1, ...
    noLensGrid.Ny / 2, ...
    noLensGrid.Nz / 2]);
sourceKwaveM = [ ...
    noLensGrid.x_vec(sourceIndex(1)); ...
    noLensGrid.y_vec(sourceIndex(2)); ...
    noLensGrid.z_vec(sourceIndex(3))];

worldFromKwaveM = eye(4);
worldFromKwaveM(1:3, 4) = ...
    sourceAtlasM - sourceKwaveM;

firstWorldM = worldFromKwaveM * [ ...
    noLensGrid.x_vec(1); ...
    noLensGrid.y_vec(1); ...
    noLensGrid.z_vec(1); ...
    1];

geometry.size = gridSize;
geometry.spacingM = ...
    [spacingM, spacingM, spacingM];
geometry.originM = firstWorldM(1:3).';
geometry.worldFromKwaveM = worldFromKwaveM;
geometry.targetAtlasM = targetAtlasM.';
geometry.sourceAtlasM = sourceAtlasM.';
end

function setSimulationTime( ...
    kgrid, medium, simulationConfig)

maximumSoundSpeed = ...
    max(medium.sound_speed, [], 'all');

timeStepS = ...
    simulationConfig.solver.cfl * ...
    kgrid.dx / maximumSoundSpeed;

durationS = simulationConfig.solver.durationS;
numberOfTimeSteps = ...
    floor(durationS / timeStepS) + 1;

kgrid.setTime(numberOfTimeSteps, timeStepS);
end
