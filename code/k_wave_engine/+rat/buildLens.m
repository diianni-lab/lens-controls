function [masks, lensInfo] = buildLens( ...
    kgrid, simulationConfig)

masks.device = bowlMask( ...
    kgrid, simulationConfig.transducer);
masks.element = masks.device;
masks.elementLabels = uint8(masks.element);
[masks.lens, lensInfo] = sphericalLensMask( ...
    kgrid, simulationConfig);
end

function mask = bowlMask(kgrid, transducer)

radiusGrid = round( ...
    transducer.radiusOfCurvatureM / kgrid.dx);
diameterGrid = ...
    floor(transducer.diameterM / ...
    kgrid.dx / 2) * 2 + 1;

sourcePosition = round([ ...
    1, kgrid.Ny / 2, kgrid.Nz / 2]);
focusPosition = round([ ...
    kgrid.Nx / 2, ...
    kgrid.Ny / 2, ...
    kgrid.Nz / 2]);

mask = makeBowl( ...
    [kgrid.Nx, kgrid.Ny, kgrid.Nz], ...
    sourcePosition, ...
    radiusGrid, ...
    diameterGrid, ...
    focusPosition, ...
    'Plot', false) > 0;

centralHole = ...
    kgrid.y .^ 2 + kgrid.z .^ 2 <= ...
    (transducer.centralHoleDiameterM / 2) ^ 2;
mask = mask & ~centralHole;
end

function [mask, lensInfo] = sphericalLensMask( ...
    kgrid, simulationConfig)

transducer = simulationConfig.transducer;
lens = simulationConfig.lens;

[xKwaveM, yKwaveM, zKwaveM] = ndgrid( ...
    kgrid.x_vec, ...
    kgrid.y_vec, ...
    kgrid.z_vec);

sourcePosition = round([ ...
    1, kgrid.Ny / 2, kgrid.Nz / 2]);
sourceCenterM = [ ...
    kgrid.x_vec(sourcePosition(1)), ...
    kgrid.y_vec(sourcePosition(2)), ...
    kgrid.z_vec(sourcePosition(3))];

focusCenterM = sourceCenterM + [ ...
    transducer.sourceToTargetDistanceM, 0, 0];

focusToSource = ...
    sourceCenterM - focusCenterM;
focusToSource = ...
    focusToSource / norm(focusToSource);

apertureRadiusM = transducer.diameterM / 2;
coneHalfAngle = asin( ...
    apertureRadiusM / ...
    transducer.sourceToTargetDistanceM) .* ...
    lens.coneAngleMultiplier;

xFromFocusM = xKwaveM - focusCenterM(1);
yFromFocusM = yKwaveM - focusCenterM(2);
zFromFocusM = zKwaveM - focusCenterM(3);

radiusFromFocusM = sqrt( ...
    xFromFocusM .^ 2 + ...
    yFromFocusM .^ 2 + ...
    zFromFocusM .^ 2);

distanceTowardSourceM = ...
    xFromFocusM .* focusToSource(1) + ...
    yFromFocusM .* focusToSource(2) + ...
    zFromFocusM .* focusToSource(3);

cosineFromSourceAxis = ...
    distanceTowardSourceM ./ ...
    (radiusFromFocusM + eps);

insideCone = ...
    distanceTowardSourceM > 0 & ...
    cosineFromSourceAxis >= cos(coneHalfAngle);

pillarMap = tiledPillarMap(kgrid, lens);
thicknessMapM = ...
    single(lens.baseThicknessM) + ...
    single(lens.maximumThicknessM - ...
        lens.baseThicknessM) .* ...
    pillarMap;
thicknessM = repmat( ...
    reshape(thicknessMapM, ...
    [1, kgrid.Ny, kgrid.Nz]), ...
    [kgrid.Nx, 1, 1]);

apertureMask = squeeze(any(insideCone, 1));
reportedThicknessMapM = ...
    lens.baseThicknessM + ...
    (lens.maximumThicknessM - ...
        lens.baseThicknessM) .* ...
    pillarMap;
lensInfo.meanThicknessM = mean( ...
    reportedThicknessMapM(apertureMask));

outerRadiusM = ...
    transducer.radiusOfCurvatureM - ...
    lens.distanceM;

mask = ...
    radiusFromFocusM <= outerRadiusM & ...
    radiusFromFocusM >= ...
    outerRadiusM - thicknessM & ...
    insideCone;
end

function pillarMap = tiledPillarMap(kgrid, lens)

tileY = round( ...
    lens.pillarWidthMm * 1e-3 / kgrid.dy);
tileZ = round( ...
    lens.pillarWidthMm * 1e-3 / kgrid.dz);

numberOfTilesY = ceil(kgrid.Ny / tileY);
numberOfTilesZ = ceil(kgrid.Nz / tileZ);

stream = RandStream( ...
    'threefry', 'Seed', lens.seed);
weights = rand( ...
    stream, ...
    numberOfTilesY, ...
    numberOfTilesZ, ...
    'single');

pillarMap = repelem(weights, tileY, tileZ);
pillarMap = pillarMap( ...
    1:kgrid.Ny, 1:kgrid.Nz);
end
